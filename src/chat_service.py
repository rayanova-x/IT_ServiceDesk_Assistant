"""
Single entry point a UI backend calls per user message: runs the real
pipeline (Steps 0-9), logs every turn to session_store.py, and returns
plain data the UI can render directly. No new pipeline logic here --
purely wiring + persistence, same convention as pipeline.py itself
("this module is ONLY the wiring").

One call to send_message() may log MULTIPLE turns to session_store.py
(one per PipelineResult) if the message was a compound/bundled query --
same convention run_pipeline() already uses for search_results.
"""

import logging
import time
import uuid
from dataclasses import dataclass, field

import jira_client
import live_events
import session_store
from gemini_retry import GeminiUnavailableError
from pii_redaction import redact_for_storage
from pipeline import PipelineClients, run_pipeline
from step0_context import ConversationState
from step9_generation import StreamInterrupted, generate_answer_streaming

logger = logging.getLogger("chat_service")


@dataclass
class ChatTurnDisplay:
    """One sub-result's worth of UI-ready content."""
    sub_query: str
    mode: str | None  # None if stopped_at != "ok"
    answer_text: str | None
    caveat: str | None
    staleness_disclosure: str
    superseded_alternatives: list  # list[dict] -- plain dicts as of the 2026-10-24 streaming refactor, not SupersededAlternative objects
    low_confidence: bool | None
    # Added 2026-10-24 for the citation side-panel: structured per-
    # citation data (page_id/title/header_path), not just the flat
    # staleness_disclosure string, so the UI can render each one as a
    # clickable chip that opens article_lookup.py's content.
    citations: list  # list[dict] -- {"page_id", "title", "header_path"}


@dataclass
class ChatResponse:
    stopped_at: str  # "declined" | "ok" | "error"
    turns: list[ChatTurnDisplay] = field(default_factory=list)
    error_message: str | None = None  # set only when stopped_at == "error"
    # Set when stopped_at == "declined" -- the direct reply text for that
    # turn, generated by the single routing+search reasoning call. See
    # pipeline.py's PipelineOutcome.message.
    message: str | None = None


def new_session_id() -> str:
    return str(uuid.uuid4())


def ticket_session_id(issue_key: str, session_number: int = 1) -> str:
    """
    Session identity for a ticket-attached session IS the Jira issue
    key, not a random UUID -- so reopening the same accepted ticket
    next week resumes the same conversation instead of starting fresh.
    See PROJECT_HANDOFF.md for the "one persistent session per accepted
    ticket" design decision.

    session_number: added 2026-10-25 -- a ticket can now have MULTIPLE
    sessions (a real product feature: "start a new session on this
    ticket" without losing the old one's history). session_number=1 is
    the ORIGINAL session and is DELIBERATELY unsuffixed
    ("jira:IH-1", not "jira:IH-1::1") so every session_id already in
    sessions.db from before this feature existed keeps resolving
    correctly -- no migration needed, no existing data silently
    orphaned. session_number>=2 appends "::N" (double-colon, not "#" --
    a literal "#" in a URL path segment gets truncated by the browser as
    a fragment identifier, which would have silently broken
    /api/sessions/{session_id}/turns and .../close for any session past
    the first).
    """
    base = f"jira:{issue_key}"
    return base if session_number <= 1 else f"{base}::{session_number}"


def start_or_resume_ticket_session_streaming(
    issue_key: str,
    conversation_state: ConversationState,
    clients: PipelineClients,
    allowed_groups: set[str] | None = None,
    session_number: int = 1,
):
    """
    Streaming counterpart to start_or_resume_ticket_session() -- see
    stream_message()'s own docstring for the real-streaming design. Same
    message_source="ticket" reasoning as the non-streaming version.

    session_number: which of this ticket's (possibly several) sessions
    to seed -- see ticket_session_id()'s own docstring for the real
    product feature this serves ("start a new session on this ticket").
    Always re-seeds with the SAME ticket content regardless of
    session_number (a fresh session on the same ticket still needs the
    ticket's real description/comments as its first message) -- the
    caller is responsible for only calling this when session_number is
    genuinely new/unseeded, same idempotency contract as before.

    Deliberately NOT a generator function itself (no `yield` in this
    function's own body) -- the Jira fetch (jira_client.get_issue(),
    which can raise JiraFetchError) runs EAGERLY here, before returning,
    rather than lazily on first iteration. If this were a bare generator
    function, a caller's try/except around calling it would never catch
    a JiraFetchError raised inside -- a generator function's body only
    actually runs once iteration starts, which for an HTTP streaming
    response may be too late to cleanly return a different status code
    (e.g. 502) instead of a stream that's already begun.
    """
    issue = jira_client.get_issue(issue_key)
    seed_message = issue.to_seed_message()
    session_id = ticket_session_id(issue_key, session_number)
    return stream_message(session_id, seed_message, conversation_state, clients,
                           allowed_groups=allowed_groups, message_source="ticket")


def start_or_resume_ticket_session(
    issue_key: str,
    conversation_state: ConversationState,
    clients: PipelineClients,
    allowed_groups: set[str] | None = None,
) -> ChatResponse:
    """
    Called when an IT staffer opens/accepts a ticket for the first
    time in this session's lifetime: fetches the ticket's real content
    (summary, description, comments, status) from Jira and feeds it as
    the FIRST message of that ticket's session -- the "genuinely new"
    piece of this integration, per the design decision to avoid
    building a second, redundant summarization step (the existing
    Steps 1-9 pipeline already turns a raw message into an understood,
    answered problem; this function's only job is constructing that
    raw message from real Jira content instead of requiring the
    staffer to re-type it).

    Non-streaming variant: fully drains start_or_resume_ticket_session_streaming()
    and assembles one complete ChatResponse. See stream_message()'s own
    docstring for why both variants exist rather than one function with a
    mode flag.

    Idempotent per the caller's session lifecycle: this should only be
    called ONCE per ticket session (when first opened), not on every
    subsequent message in that session -- the caller (ui/server.py) is
    responsible for tracking whether a given ticket session has already
    been seeded, same as it already tracks live ConversationState
    objects per session_id.
    """
    session_id = ticket_session_id(issue_key)
    events = list(start_or_resume_ticket_session_streaming(
        issue_key, conversation_state, clients, allowed_groups=allowed_groups,
    ))
    return _assemble_chat_response(session_id, events)


def send_message(
    session_id: str,
    raw_message: str,
    conversation_state: ConversationState,
    clients: PipelineClients,
    allowed_groups: set[str] | None = None,
    username: str | None = None,
    message_source: str = "user_message",
) -> ChatResponse:
    """
    Non-streaming entry point: fully drains stream_message() and
    assembles one complete ChatResponse, for callers that don't need
    incremental delivery (POST /api/messages). See stream_message() for
    the real logic and why BOTH variants exist.
    """
    events = list(stream_message(session_id, raw_message, conversation_state, clients,
                                  allowed_groups=allowed_groups, username=username,
                                  message_source=message_source))
    return _assemble_chat_response(session_id, events)


def _assemble_chat_response(session_id: str, events: list[dict]) -> ChatResponse:
    """Reduces a fully-drained stream_message()/start_or_resume_ticket_session_streaming()
    event list into one ChatResponse -- reassembling turn_delta pieces
    back into complete answer_text per turn, for a non-streaming caller."""
    meta = next(e for e in events if e["type"] == "meta")
    if meta["stopped_at"] == "error":
        return ChatResponse(stopped_at="error", turns=[], error_message=meta["error_message"])
    if meta["stopped_at"] == "declined":
        return ChatResponse(stopped_at="declined", turns=[], message=meta["message"])

    turns_by_index: dict[int, dict] = {}
    for e in events:
        if e["type"] == "turn_start":
            turns_by_index[e["turn_index"]] = {**e["turn"], "answer_text": ""}
        elif e["type"] == "turn_delta":
            turns_by_index[e["turn_index"]]["answer_text"] += e["delta"]
        elif e["type"] == "turn_end" and e.get("turn"):
            # turn_end carries citations/caveat/staleness for a
            # synthesized answer, only known once the full text streamed
            # -- merge over the turn_start payload, same as the frontend
            # does (see ui/static/index.html's identical merge).
            turns_by_index[e["turn_index"]].update(e["turn"])

    turns = [
        ChatTurnDisplay(
            sub_query=t["sub_query"], mode=t["mode"],
            answer_text=t["answer_text"] or None, caveat=t["caveat"],
            staleness_disclosure=t["staleness_disclosure"],
            superseded_alternatives=t["superseded_alternatives"],
            low_confidence=t["low_confidence"], citations=t["citations"],
        )
        for _, t in sorted(turns_by_index.items())
    ]
    return ChatResponse(stopped_at="ok", turns=turns)


def stream_message(
    session_id: str,
    raw_message: str,
    conversation_state: ConversationState,
    clients: PipelineClients,
    allowed_groups: set[str] | None = None,
    username: str | None = None,
    message_source: str = "user_message",
):
    """
    Core entry point (generator): runs the real pipeline, streams
    generation chunks AS THEY'RE PRODUCED by the model, and logs every
    resulting turn to session_store.py once each one's final text is
    known. Yields event dicts: {"type": "meta", ...} once up front, then
    per search result {"type": "turn_start", ...} / repeated
    {"type": "turn_delta", ...} / {"type": "turn_end", ...}, in that
    order -- mirrors the SSE event vocabulary ui/server.py already uses,
    so that layer mostly just forwards these rather than re-deriving them.

    REAL STREAMING, added 2026-10-24 -- replaces the old design where
    ui/server.py faked streaming by slicing an ALREADY-COMPLETE answer
    into fixed-size chunks purely for visual effect, because the old
    generate_answer() ran synthesis to completion before anything could
    be shown. Verified directly before this change (see
    step9_generation.py's generate_answer_streaming() docstring) that
    this project's verify-then-retract faithfulness check is a single
    prompt instruction within one generation call, not a second
    round-trip -- so there's no separate verification step being lost by
    streaming the first call's own output.

    send_message()/start_or_resume_ticket_session() above are thin
    non-streaming wrappers that fully drain this generator -- kept as
    SEPARATE functions from this one (not a single function with a
    streaming/non-streaming flag) so neither caller shape has to reason
    about the other; the logging/redaction/access-denial logic below is
    identical either way, written once here.

    allowed_groups/username: Step 4.5 identity, resolved server-side by
    the caller (ui/server.py, from the login session cookie) -- never
    trusted from client request data. None/None preserves the old
    unfiltered behavior for any caller that doesn't pass an identity
    (e.g. offline scripts).

    message_source: passed straight to run_pipeline() -- see its
    docstring. Defaults to "user_message" for the normal typed-message
    path; start_or_resume_ticket_session() above overrides it to
    "ticket" for a ticket's seed content specifically.
    """
    session_store.create_session(session_id, conversation_state.case_facts)

    # Must check has_context() BEFORE run_pipeline() runs -- run_pipeline()
    # calls add_turn("user", raw_message) internally as a side effect, so
    # checking AFTER would always see the just-added message and wrongly
    # report used_step0=True even on a genuine first message. Bug found
    # while smoke-testing this module 2026-09-18: PipelineOutcome doesn't
    # expose ContextResult.used_step0 directly, so this is the correct
    # way to capture the true pre-call state without a second (wasted)
    # contextualize() call.
    used_step0 = conversation_state.has_context()

    # Every Gemini call anywhere in run_pipeline()/generate_answer() below
    # (Steps 0/2/3/9) goes through gemini_retry.call_with_retry() first --
    # a transient 429/503/timeout is retried there. GeminiUnavailableError
    # only reaches here once retries are genuinely exhausted, meaning
    # Gemini is actually down/rate-limited for longer than a few seconds'
    # backoff can ride out. Converted to a clean "error" ChatResponse
    # instead of propagating -- an unhandled exception here would 500 the
    # whole HTTP request with a stack trace, which is a real pilot outage,
    # not a cosmetic issue, for a tool real IT staff are using live.
    try:
        outcome = run_pipeline(raw_message, clients, conversation_state=conversation_state,
                                allowed_groups=allowed_groups, message_source=message_source)
    except GeminiUnavailableError as e:
        logger.error("stream_message: Gemini unavailable during %s: %s", e.stage,
                     e.original, extra={"session_id": session_id, "username": username, "stage": e.stage})
        session_store.log_turn(
            session_id=session_id,
            raw_text=redact_for_storage(raw_message),
            standalone_text=None,
            used_step0=used_step0,
            stopped_at="error",
        )
        live_events.broadcast("turn_completed", {
            "session_id": session_id, "username": username, "stopped_at": "error",
            "stage": e.stage, "category": None, "mode": None, "low_confidence": None,
        })
        yield {
            "type": "meta", "session_id": session_id, "stopped_at": "error",
            "error_message": (
                "The assistant is temporarily unavailable (the AI service didn't respond "
                "after several retries). Please try again in a moment."
            ),
            "message": None,
        }
        return

    session_store.update_session_facts(session_id, conversation_state.case_facts)
    session_store.save_conversation_state(session_id, conversation_state.to_dict())

    if outcome.stopped_at != "ok":
        # Record the assistant's reply into conversation history too, not
        # just the user's message -- real gap found 2026-10-24 via a
        # review flow diagram: without this, Step 0 on the NEXT turn has
        # no idea the bot already declined/acknowledged the previous
        # message, since conversational/off_topic turns never reached
        # add_turn("assistant", ...) before. genuine_question's "ok" path
        # already does this further down (conversation_state.add_turn for
        # the generated answer); this closes the same gap for the other
        # two stop reasons.
        if outcome.message:
            conversation_state.add_turn("assistant", outcome.message)
            session_store.save_conversation_state(session_id, conversation_state.to_dict())
        session_store.log_turn(
            session_id=session_id,
            raw_text=redact_for_storage(raw_message),
            standalone_text=None,
            used_step0=used_step0,
            stopped_at=outcome.stopped_at,
            answer_text=redact_for_storage(outcome.message),
            latency_ms=outcome.stage_latency_ms,
        )
        live_events.broadcast("turn_completed", {
            "session_id": session_id, "username": username, "stopped_at": outcome.stopped_at,
            "category": None, "mode": None, "low_confidence": None,
        })
        yield {
            "type": "meta", "session_id": session_id, "stopped_at": outcome.stopped_at,
            "error_message": None, "message": outcome.message,
        }
        return

    yield {"type": "meta", "session_id": session_id, "stopped_at": "ok", "error_message": None, "message": None}

    assistant_reply_parts = []
    for turn_index, r in enumerate(outcome.results):
        if r.access_denial:
            session_store.log_access_denial(
                session_id=session_id,
                username=username,
                sub_query=redact_for_storage(r.sub_query),
                excluded_groups=r.access_denial["excluded_groups"],
                excluded_count=r.access_denial["excluded_count"],
            )
            live_events.broadcast("access_denied", {
                "session_id": session_id, "username": username, "sub_query": r.sub_query,
                "excluded_groups": r.access_denial["excluded_groups"],
                "excluded_count": r.access_denial["excluded_count"],
            })

        gen_start = time.perf_counter()
        try:
            streamed = generate_answer_streaming(
                r.sub_query, r.search_results, r.low_confidence, client=clients.gemini,
                low_confidence_reason=r.low_confidence_reason, category=r.category_used,
                confidence_top_score=r.confidence_top_score, confidence_threshold=r.confidence_threshold,
            )
        except GeminiUnavailableError as e:
            # Retrieval (the expensive, already-done part) succeeded --
            # only the generation call failed BEFORE any chunk was
            # produced. Degrade just THIS sub-result to a
            # candidates_only-shaped turn with an error caveat, rather
            # than discarding a compound query's other, already-
            # successful sub-results along with it.
            logger.error("stream_message: Gemini unavailable during %s: %s", e.stage, e.original,
                         extra={"session_id": session_id, "username": username, "stage": e.stage})
            from step9_generation import GenerationResult, _citations_from
            gen = GenerationResult(
                mode="candidates_only",
                answer_text=None,
                citations=_citations_from(r.search_results),
                caveat=(
                    "The assistant could not generate an answer right now (the AI service "
                    "didn't respond after several retries) -- showing the raw ranked "
                    "candidates below instead."
                ),
            )
            text_chunks = None
        else:
            gen = streamed.result if streamed.mode == "candidates_only" else None  # finalized below if synthesized
            text_chunks = streamed.text_chunks if streamed.mode == "synthesized" else None
            source_for_head = streamed.result if streamed.mode == "candidates_only" else None

        # turn_start/turn_end are ALWAYS emitted regardless of which
        # branch above ran -- real bug found and fixed 2026-10-24: an
        # earlier version of this only emitted them inside the success
        # branch, so a generation failure silently produced a turn with
        # NO turn_start/turn_end at all, and the degraded candidates_only
        # result never reached the caller (caught by
        # tests/test_error_handling.py's generation-outage check).
        if gen is not None:
            # Either candidates_only from the start (low confidence/no
            # results/generation failure) -- citations/caveat already final.
            head_citations = [
                {"page_id": c.page_id, "title": c.title, "header_path": c.header_path,
                 "last_updated": c.last_updated, "status": c.status}
                for c in gen.citations
            ]
            yield {
                "type": "turn_start", "turn_index": turn_index,
                "turn": {
                    "sub_query": r.sub_query, "mode": gen.mode, "caveat": gen.caveat,
                    "staleness_disclosure": gen.staleness_disclosure,
                    "superseded_alternatives": [
                        {
                            "current_page_id": a.current_page_id, "older_page_id": a.older_page_id,
                            "older_title": a.older_title, "older_last_updated": a.older_last_updated,
                            "current_last_updated": a.current_last_updated,
                        }
                        for a in gen.superseded_alternatives
                    ],
                    "low_confidence": r.low_confidence, "citations": head_citations,
                },
            }
            yield {"type": "turn_end", "turn_index": turn_index}
        else:
            # Synthesized -- stream real chunks, then finalize.
            yield {
                "type": "turn_start", "turn_index": turn_index,
                "turn": {
                    "sub_query": r.sub_query, "mode": "synthesized", "caveat": None,
                    "staleness_disclosure": "", "superseded_alternatives": [],
                    "low_confidence": r.low_confidence, "citations": [],
                },
            }
            try:
                for chunk_text in text_chunks:
                    yield {"type": "turn_delta", "turn_index": turn_index, "delta": chunk_text}
            except StreamInterrupted as e:
                # Some text already reached the browser -- do NOT retry
                # (see StreamInterrupted's own docstring). Surface a clear
                # interruption marker instead of silently truncating; the
                # caller renders this as a visible note, not a crash.
                logger.error("stream_message: generation stream interrupted: %s", e.original,
                             extra={"session_id": session_id, "username": username})
                yield {
                    "type": "turn_delta", "turn_index": turn_index,
                    "delta": "\n\n[Response interrupted -- please try again.]",
                }
            gen = streamed.finish()
            # Citations/citation_accuracy/staleness are only known once
            # the FULL text is in (citation_accuracy_from() checks the
            # complete answer against what was actually cited) -- sent
            # here, in turn_end, rather than turn_start, since turn_start
            # fires before any text has streamed. The frontend merges
            # this over its earlier (empty-citations) turn_start payload
            # before rendering the citation chips.
            yield {
                "type": "turn_end", "turn_index": turn_index,
                "turn": {
                    "caveat": gen.caveat,
                    "staleness_disclosure": gen.staleness_disclosure,
                    "superseded_alternatives": [
                        {
                            "current_page_id": a.current_page_id, "older_page_id": a.older_page_id,
                            "older_title": a.older_title, "older_last_updated": a.older_last_updated,
                            "current_last_updated": a.current_last_updated,
                        }
                        for a in gen.superseded_alternatives
                    ],
                    "citations": [
                        {"page_id": c.page_id, "title": c.title, "header_path": c.header_path,
                         "last_updated": c.last_updated, "status": c.status}
                        for c in gen.citations
                    ],
                },
            }

        latency_ms = dict(outcome.stage_latency_ms)
        latency_ms["step9_generation"] = round((time.perf_counter() - gen_start) * 1000, 1)

        top_score = r.search_results[0]["rerank_score"] if r.search_results else None
        # A knowledge gap is logged internally by check_confidence()/
        # log_knowledge_gap() (see step8_confidence.py, called from
        # inside run_pipeline()) whenever the CONFIDENCE signal itself
        # says not-confident -- r.low_confidence can ALSO be True purely
        # from Step 4's ambiguity gate, which does NOT write to the
        # knowledge-gap log. Approximate here without re-deriving Step 8's
        # internal confidence.confident value: a low top_rerank_score
        # (below Step 8's real threshold) is the same condition that
        # actually triggers the gap log. Uses _threshold_for() -- the
        # SAME per-category lookup check_confidence() itself uses, not a
        # flat constant -- since 2026-10-15's per-category thresholds
        # mean "below threshold" is no longer the same number for every
        # category (e.g. Software & Applications Support uses 3.0, not
        # the global 2.0). Using the stale flat constant here would have
        # silently mismatched what Step 8 actually decided for that
        # category -- a real bug, caught and fixed when the per-category
        # mechanism was added, not shipped separately from it.
        from step8_confidence import _threshold_for
        threshold = _threshold_for(r.category_used)
        knowledge_gap_logged = top_score is None or top_score < threshold

        # PII redaction happens HERE -- immediately before the write to
        # durable storage -- never earlier. Everything above this point
        # (Step 1/3 extraction, Step 9 generation) already ran on the
        # REAL, unredacted text, which is required for correct extraction
        # and a correct answer. r.sub_query/gen.answer_text/gen.caveat are
        # redacted copies made ONLY for what gets persisted; the real
        # values were already streamed to the UI for this request before
        # redaction happens (see pii_redaction.py's module docstring for
        # the full "redact the persisted copy, not the in-flight copy"
        # reasoning).
        session_store.log_turn(
            session_id=session_id,
            raw_text=redact_for_storage(raw_message),
            # standalone_text = r.sub_query -- pipeline.py's PipelineOutcome
            # doesn't expose Step 0's intermediate rewrite (the text
            # AFTER contextualization but BEFORE Step 3 further rewrites/
            # splits it into sub_query) as a separate field, only the
            # final per-sub-question sub_query. Logging sub_query here is
            # the closest real signal available without changing
            # pipeline.py's return shape -- it's Step 3's output, not
            # strictly Step 0's, but for a single-sub-query message
            # (the common case) they're effectively the same rewrite.
            standalone_text=redact_for_storage(r.sub_query),
            used_step0=used_step0,
            stopped_at="ok",
            sub_query=redact_for_storage(r.sub_query),
            category_used=r.category_used,
            wants_latest=outcome.wants_latest,
            low_confidence=r.low_confidence,
            top_rerank_score=top_score,
            mode=gen.mode,
            answer_text=redact_for_storage(gen.answer_text),
            caveat=redact_for_storage(gen.caveat),
            knowledge_gap_logged=knowledge_gap_logged,
            citations=[
                {"page_id": c.page_id, "title": c.title, "last_updated": c.last_updated,
                 "status": c.status, "header_path": c.header_path}
                for c in gen.citations
            ],
            superseded_alternatives=[
                {
                    "current_page_id": a.current_page_id, "older_page_id": a.older_page_id,
                    "older_title": a.older_title, "older_last_updated": a.older_last_updated,
                    "current_last_updated": a.current_last_updated,
                }
                for a in gen.superseded_alternatives
            ],
            citation_accuracy=gen.citation_accuracy,
            latency_ms=latency_ms,
        )

        live_events.broadcast("turn_completed", {
            "session_id": session_id, "username": username, "stopped_at": "ok",
            "category": r.category_used, "mode": gen.mode, "low_confidence": r.low_confidence,
            "total_latency_ms": round(sum(latency_ms.values()), 1),
        })

        assistant_reply_parts.append(gen.answer_text or gen.caveat or "")

    conversation_state.add_turn("assistant", "\n\n".join(assistant_reply_parts))
    # Save again AFTER add_turn("assistant", ...) above -- the earlier
    # save_conversation_state() call only captured state up through the
    # USER turn; the assistant's reply also belongs in current_turns so
    # a rehydrated session's next Step 0 rewrite has the full exchange,
    # not just half of it.
    session_store.save_conversation_state(session_id, conversation_state.to_dict())

    yield {"type": "done"}
